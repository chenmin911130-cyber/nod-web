function withModelPrompts(copy: IphoneCopy): IphoneCopy {
  return {
    ...copy,
    quickSummarizeAsk: EN_IPHONE_COPY.quickSummarizeAsk,
    quickActionItems: EN_IPHONE_COPY.quickActionItems,
    quickKeyConcepts: EN_IPHONE_COPY.quickKeyConcepts,
  }
}

export function iphoneCopyFor(lang: UiLang): IphoneCopy {
  if (lang === 'en') return { ...EN_IPHONE_COPY }
  if (lang === 'zh') return withModelPrompts({ ...ZH_IPHONE_COPY })
  const overlap = WATCH_OVERLAP[lang as WatchOverlapLang]
  return withModelPrompts({ ...EN_IPHONE_COPY, ...overlap })
}
