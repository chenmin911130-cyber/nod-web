eq(watchUiLang('pt-BR'), 'pt', 'Portuguese system uses Portuguese copy')
eq(watchUiLang('ja-JP'), 'ja', 'Japanese system uses Japanese copy')
eq(watchUiLang('ko-KR'), 'en', 'unsupported system languages fall back to English')

